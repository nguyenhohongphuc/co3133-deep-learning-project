"""Audit saved A1 test metrics and create report Section 9 tables/figures.

No model fitting or prediction is performed. Run with:
MPL_IGNORE_SYSTEM_FONTS=1 MPLCONFIGDIR=/tmp/a1-mpl-bundled .venv/bin/python scripts/a1_report/summarize_a1_quantitative.py
"""
from __future__ import annotations

import csv
import json
from math import isclose
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import Normalize
from matplotlib.ticker import PercentFormatter

from plot_a1_training_behaviour import RUNS

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "reports/a1/assets/quantitative"
CLASSES = ["T-shirt/top", "Trouser", "Pullover", "Dress", "Coat",
           "Sandal", "Shirt", "Sneaker", "Bag", "Ankle boot"]


def read_runs():
    with (ROOT / "results/a1/tables/comparison.csv").open(newline="") as stream:
        comparison = {row["run_id"]: row for row in csv.DictReader(stream)}
    runs = []
    for name, run_id, _ in RUNS:
        directory = ROOT / "results/a1/runs" / run_id
        metadata = json.loads((directory / "metrics.json").read_text())
        test = json.loads((directory / "test_metrics.json").read_text())
        cm = np.asarray(test["confusion"], dtype=np.int64)
        assert cm.shape == (10, 10) and np.all(cm >= 0)
        support, predicted, tp = cm.sum(axis=1), cm.sum(axis=0), cm.diagonal()
        assert np.all(support == 1000) and metadata["seed"] == 42
        precision = np.divide(tp, predicted, out=np.zeros(10), where=predicted != 0)
        recall = tp / support
        f1 = np.divide(2 * tp, support + predicted)
        accuracy = float(tp.sum() / cm.sum())
        macro_f1 = float(f1.mean())
        assert isclose(accuracy, test["accuracy"], abs_tol=1e-12)
        assert isclose(macro_f1, test["macro_f1"], abs_tol=1e-12)
        assert test["inference_batch_size"] == 128 and test["inference_repeats"] == 5
        assert test["device"] == metadata["device"] == "cuda"
        inference = 1000 * test["inference_time"] / int(cm.sum())
        assert isclose(inference, test["inference_ms_per_image"], abs_tol=1e-12)
        row = comparison[run_id]
        for key, actual in [("test_accuracy", accuracy), ("test_macro_f1", macro_f1),
                            ("params", metadata["param"]), ("train_time_s", metadata["train_time"]),
                            ("epochs_run", metadata["epochs_run"]),
                            ("inference_time_s", test["inference_time"])]:
            assert isclose(float(row[key]), actual, rel_tol=1e-12, abs_tol=1e-12), (run_id, key)
        runs.append(dict(
            model=name, run_id=run_id, seed=metadata["seed"], commit=metadata["commit"],
            accuracy=accuracy, macro_f1=macro_f1, params=metadata["param"],
            epochs=metadata["epochs_run"], train_time_s=metadata["train_time"],
            inference_ms_per_image=inference, n_test=int(cm.sum()),
            errors=int(cm.sum() - tp.sum()), confusion=cm.tolist(),
            per_class=[dict(class_id=k, name=CLASSES[k], support=int(support[k]),
                            predicted=int(predicted[k]), true_positive=int(tp[k]),
                            precision=float(precision[k]), recall=float(recall[k]), f1=float(f1[k]))
                       for k in range(10)]))
    return runs


def write_tables(runs):
    rows = ["% Generated by scripts/a1_report/summarize_a1_quantitative.py; do not edit numbers manually.",
            r"\begin{tabularx}{\textwidth}{@{}Yrrrrrr@{}}", r"\toprule",
            r"Configuration & \shortstack{Acc.\\(\%)} & \shortstack{Macro-F1\\(\%)} & Parameters & Epochs & \shortstack{Train\\(s)} & \shortstack{Inference\\(ms/image)} \\",
            r"\midrule"]
    for i, run in enumerate(runs):
        if i == 5:
            rows.append(r"\midrule")
        name = run["model"] + (r"\textsuperscript{\textdagger}" if i >= 5 else "")
        cells = [name, f"{100 * run['accuracy']:.2f}", f"{100 * run['macro_f1']:.2f}",
                 f"{run['params']:,}", str(run["epochs"]), f"{run['train_time_s']:.1f}",
                 f"{run['inference_ms_per_image']:.5f}"]
        if run["model"] == "CNN":
            cells[1:3] = [r"\textbf{" + cell + "}" for cell in cells[1:3]]
        rows.append(" & ".join(cells) + r" \\")
    rows.extend([r"\bottomrule", r"\end{tabularx}"])
    (OUT / "model_comparison.tex").write_text("\n".join(rows) + "\n")
    rows = ["% Generated from saved test confusion matrices.",
            r"\begin{tabularx}{\textwidth}{@{}Yrrrrr@{}}", r"\toprule",
            r"Class & Linear & MLP & CNN & \shortstack{LSTM\\rows} & Transformer \\",
            r"\midrule"]
    for k, name in enumerate(CLASSES):
        values = [run["per_class"][k]["f1"] for run in runs[:5]]
        maximum = max(values)
        cells = [name]
        for value in values:
            cell = f"{100 * value:.2f}"
            cells.append(r"\textbf{" + cell + "}" if value == maximum else cell)
        rows.append(" & ".join(cells) + r" \\")
    rows.extend([r"\bottomrule", r"\end{tabularx}"])
    (OUT / "classwise_f1.tex").write_text("\n".join(rows) + "\n")


def plot_confusions(runs):
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 11,
                         "axes.titlesize": 13, "axes.titleweight": "bold",
                         "axes.labelsize": 11, "xtick.labelsize": 10,
                         "ytick.labelsize": 10, "text.color": "#253649"})
    fig, axes = plt.subplots(3, 2, figsize=(9.4, 11.2), layout="constrained")
    for letter, ax, run in zip("abcde", axes.flat, runs[:5]):
        cm = np.asarray(run["confusion"])
        rates = cm / cm.sum(axis=1, keepdims=True)
        ax.imshow(rates, cmap="Blues", vmin=0, vmax=1, interpolation="nearest")
        for i in range(10):
            for j in range(10):
                if i == j or rates[i, j] >= 0.02:
                    ax.text(j, i, f"{rates[i,j]*100:.0f}", ha="center", va="center",
                            fontsize=9, color="white" if rates[i, j] > 0.5 else "#253649")
        ax.set(title=f"({letter}) {run['model']}", xlabel="Predicted class ID",
               ylabel="True class ID", xticks=range(10), yticks=range(10))
        ax.tick_params(length=0)
        for spine in ax.spines.values():
            spine.set_color("#CDD6DF")
    key = axes.flat[-1]
    key.axis("off")
    key.text(0.03, 0.96, "CLASS IDs AND SCALE", fontsize=12, weight="bold",
             transform=key.transAxes, va="top")
    for k, name in enumerate(CLASSES):
        key.text(0.03, 0.84 - 0.055 * k, f"{k}  {name}", fontsize=11,
                 transform=key.transAxes, va="top")
    key.text(0.03, 0.27,
             "Row-normalized; 1,000 examples per row.\n"
             "Labels: diagonal and off-diagonal >= 2%.\n"
             "Values: rounded integer percentages.",
             fontsize=9.5, linespacing=1.4, transform=key.transAxes, va="top")
    bar = key.inset_axes([0.03, 0.025, 0.88, 0.035])
    fig.colorbar(plt.cm.ScalarMappable(norm=Normalize(0, 1), cmap="Blues"),
                 cax=bar, orientation="horizontal", ticks=[0, .25, .5, .75, 1],
                 format=PercentFormatter(1, decimals=0))
    bar.tick_params(labelsize=10, length=2)
    for ext in ("png", "svg"):
        fig.savefig(OUT / f"main_model_confusions.{ext}", dpi=300, facecolor="white")
    plt.close(fig)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    runs = read_runs()
    write_tables(runs)
    plot_confusions(runs)
    audit = dict(purpose="Recomputed from saved test confusion matrices; no new predictions.",
                 checks="All seven matrices reproduce saved accuracy/macro-F1 and comparison.csv; timing units agree.",
                 n_training_seeds_per_configuration=1, runs=runs)
    (ROOT / "results/a1/tables/a1_quantitative_verification.json").write_text(
        json.dumps(audit, indent=2) + "\n")
    with (ROOT / "results/a1/tables/a1_classwise_metrics.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=["model", "run_id", "seed", "class_id", "name",
                                                    "support", "predicted", "true_positive",
                                                    "precision", "recall", "f1"])
        writer.writeheader()
        for run in runs:
            for row in run["per_class"]:
                writer.writerow(dict(model=run["model"], run_id=run["run_id"], seed=run["seed"], **row))
    print("Verified 7 saved runs, 70 class records; wrote 2 LaTeX tables and confusion PNG/SVG.")
    print((OUT / "model_comparison.tex").read_text())
    print((OUT / "classwise_f1.tex").read_text())


if __name__ == "__main__":
    main()
