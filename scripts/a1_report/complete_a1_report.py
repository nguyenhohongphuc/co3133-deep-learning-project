ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "reports/a1/assets/final"
TABLES = ROOT / "results/a1/tables"
G, F = set([0, 2, 3, 4, 6]), set([5, 7, 9])


def table(name, columns, header, rows):
    lines = ["% Generated by scripts/a1_report/complete_a1_report.py from saved evidence.",
             r"\begin{tabularx}{\textwidth}{" + columns + "}", r"\toprule",
             header + r" \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabularx}"]
    (OUT / name).write_text("\n".join(lines) + "\n")


def save(fig, stem):
    for extension in ("png", "svg"):
        fig.savefig(OUT / f"{stem}.{extension}", dpi=300, facecolor="white")
    plt.close(fig)


def error_analysis(runs, images):
    cnn = next(r for r in runs if r["model"] == "CNN")
    cm, errors = np.array(cnn["confusion"]), cnn["errors"]
    counts = [sum(cm[i, j] for i in G for j in G if i != j),
              sum(cm[i, j] for i in F for j in F if i != j)]
    counts.append(errors - sum(counts))
    assert counts == [678, 79, 61] and sum(counts) == errors
    rows = [f"{name} & {int(n)} & {100*n/errors:.2f} & {100*n/10000:.2f}" + r" \\"
            for name, n in zip(["Within garment group $G$", "Within footwear group $F$", "All other confusions"], counts)]
    rows.append(r"\midrule")
    rows.append(f"All CNN errors & {errors} & 100.00 & {100*errors/10000:.2f}"+r" \\")
    table("error_taxonomy.tex", "@{}Yrrr@{}",
          r"Error group & Count & \shortstack{Share of\\errors (\%)} & \shortstack{Share of\\test set (\%)}", rows)
    directed = sorted([(int(cm[i, j]), i, j) for i in range(10) for j in range(10) if i != j],
                      key=lambda row: (-row[0], row[1], row[2]))[:8]
    rows = [f"{CLASSES[i]} & {CLASSES[j]} & {n} & {n/10:.1f} & {100*n/errors:.2f}" + r" \\"
            for n, i, j in directed]
    table("top_confusions.tex", "@{}YYrrr@{}",
          r"True class & Predicted class & Count & \shortstack{True-class\\rate (\%)} & \shortstack{Share of\\all errors (\%)}", rows)
    panel_audit = json.loads((TABLES / "a1_comparison_examples.json").read_text())["panels"]
    cases = []
    for idx in [40, 68, 32]:
        row, = [p for p in panel_audit if p["model"] == "CNN" and p["test_index"] == idx]
        assert row["kind"] == "wrong"
        cases.append(row)
    assert (cases[-1]["true"], cases[-1]["pred"]) == (3, 1)
    fig, axes = plt.subplots(1, 3, figsize=(10.5, 3.9))
    fig.subplots_adjust(left=.025, right=.975, top=.84, bottom=.24, wspace=.18)
    for ax, group, case in zip(axes, ["Within G", "Within F", "Other"], cases):
        ax.imshow(images[case["test_index"]], cmap="gray", vmin=0, vmax=255,
                  interpolation="nearest")
        ax.axis("off")
        ax.set_title(f"{group}: test #{case['test_index']}\nCNN", fontsize=12, weight="bold")
        ax.text(.5, -.06, f"True: {CLASSES[case['true']]}", ha="center", va="top",
                 fontsize=11.5, transform=ax.transAxes)
        ax.text(.5, -.19, f"Pred: {CLASSES[case['pred']]}", ha="center", va="top",
                 fontsize=11.5, color="#B04D32", transform=ax.transAxes)
    save(fig, "error_group_examples")
    (TABLES / "a1_error_analysis.json").write_text(json.dumps(dict(
        model="CNN", run_id=cnn["run_id"], n_test=10000, errors=errors,
        definitions=dict(garment_group=sorted(G), footwear_group=sorted(F),
                         residual="Every other off-diagonal entry; buckets are disjoint and exhaustive."),
        category_counts=list(map(int, counts)),
        top_directed_confusions=[dict(count=n, true=i, pred=j) for n, i, j in directed],
        top_eight_error_count=sum(n for n, _, _ in directed),
        examples=cases,
        interpretation="Counts classify label pairs, not causal visual attributes. No new predictions."), indent=2)+"\n")


def extensions(runs):
    row = next(r for r in runs if r["model"] == "LSTM rows")
    rows = []
    for name in ["LSTM columns", "LSTM patches"]:
        run = next(r for r in runs if r["model"] == name)
        values = [name.removeprefix("LSTM ").capitalize(),
                  f"{100*(run['accuracy']-row['accuracy']):+.2f}",
                  f"{100*(run['macro_f1']-row['macro_f1']):+.2f}",
                  f"{100*(run['params']/row['params']-1):+.1f}",
                  f"{100*(run['inference_ms_per_image']/row['inference_ms_per_image']-1):+.1f}"]
        rows.append(" & ".join(values)+r" \\")
    table("representation_deltas.tex", "@{}Yrrrr@{}",
          r"Variant & \shortstack{Acc. change\\(points)} & \shortstack{F1 change\\(points)} & \shortstack{Parameter\\change (\%)} & \shortstack{Inference\\change (\%)}", rows)
    selected = [next(r for r in runs if r["model"] == name)
                for name in ["LSTM columns", "LSTM patches"]]
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 4.0), layout="constrained")
    for ax, run in zip(axes, selected):
        rates = np.asarray(run["confusion"])/1000
        im = ax.imshow(rates, cmap="Blues", vmin=0, vmax=1, interpolation="nearest")
        for i in range(10):
            for j in range(10):
                if i == j or rates[i,j] >= .02:
                    ax.text(j, i, f"{100*rates[i,j]:.0f}", fontsize=9,
                            color="white" if rates[i,j] > .5 else "#253649", ha="center", va="center")
        ax.set(title=run["model"], xticks=range(10), yticks=range(10),
               xlabel="Predicted class ID", ylabel="True class ID")
        ax.tick_params(length=0)
    fig.colorbar(im, ax=axes, shrink=.8, label="Fraction of true class")
    save(fig, "additional_lstm_confusions")


def reproducibility(runs):
    head = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    original = subprocess.check_output(["git", "rev-parse", "c1747a1"], cwd=ROOT, text=True).strip()
    changed = subprocess.check_output(["git", "diff", "--name-only", original, head, "--", "src", "configs"],
                                      cwd=ROOT, text=True).splitlines()
    a1_paths = ["src/models/__init__.py", "src/models/linear.py", "src/models/mlp.py",
                "src/models/cnn.py", "src/models/rnn.py", "src/models/transformer.py",
                "src/data/fashion_mnist.py", "src/data/split.py", "src/data/loaders.py",
                "src/data/transforms.py", "src/utils", "src/engine", "src/train.py",
                "src/evaluate.py", "configs/a1.yaml"]
    a1_changed = subprocess.check_output(
        ["git", "diff", "--name-only", original, head, "--", *a1_paths],
        cwd=ROOT, text=True).splitlines()
    assert a1_changed == ["src/evaluate.py"], a1_changed
    paths = [ROOT / "results/a1/splits/split_seed42.json", ROOT/"configs/a1.yaml",
             ROOT/"requirements.txt", ROOT/"requirements.lock.txt"]
    paths += sorted((ROOT/"src").rglob("*.py"))
    paths += sorted((ROOT/"scripts").glob("*.py"))
    paths += sorted((ROOT/"scripts/a1_report").glob("*.py"))
    inventory, rows = [], []
    for run in runs:
        directory = ROOT / f"results/a1/runs/{run['run_id']}"
        files = [directory/name for name in ["config.yaml", "metrics.json", "history.csv", "test_metrics.json"]]
        paths += files
        checkpoint = directory/"best.pt"
        if checkpoint.is_file():
            paths.append(checkpoint)
        metadata = json.loads((directory/"metrics.json").read_text())
        config_hash = hashlib.sha256((directory/"config.yaml").read_bytes()).hexdigest()
        inventory.append(dict(run_id=run["run_id"], model=run["model"], seed=42,
                              training_commit=run["commit"], selected_epoch=metadata["best_epoch"],
                              epochs_run=metadata["epochs_run"], config_sha256=config_hash,
                              checkpoint_available=checkpoint.is_file(),
                              checkpoint_sha256=(hashlib.sha256(checkpoint.read_bytes()).hexdigest()
                                                 if checkpoint.is_file() else None),
                              checkpoint_bytes=(checkpoint.stat().st_size
                                                if checkpoint.is_file() else None)))
        rows.append(r"\path{"+run["run_id"]+"} & "+str(metadata["best_epoch"])+
                    r" & \texttt{"+run["commit"]+r"} & \texttt{"+config_hash[:10]+"}"+r" \\")
    table("run_traceability.tex", "@{}Yrlr@{}",
          r"Run ID (seed 42) & \shortstack{Best\\index} & Training commit & \shortstack{Config SHA-256\\prefix}", rows)
    paths += sorted((ROOT/"reports/a1").rglob("*.tex"))
    paths += [ROOT/"AI_USAGE.md", ROOT/"reports/a1/README.md", ROOT/"scripts/a1_report/README.md"]
    hashes = {str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}
    manifest = dict(purpose="Input fingerprint and availability audit for the completed A1 report; no training/evaluation.",
                    report_source_checkout=head, main_training_commit=original,
                    changes_in_src_or_configs_since_training_commit=changed,
                    a1_source_paths_compared=a1_paths,
                    changes_in_a1_sources_since_training_commit=a1_changed,
                    recorded_evaluation_revision="Not independently saved in test metadata; current evaluator is fingerprinted here.",
                    split_sha256=hashes["results/a1/splits/split_seed42.json"],
                    runs=inventory, input_sha256=hashes,
                    dependency_limits="requirements.txt is unpinned; requirements.lock.txt contains machine-local file URLs and torch 2.14.0 rather than recorded 2.14.1+cu126.")
    (TABLES/"a1_reproducibility_manifest.json").write_text(json.dumps(manifest,indent=2)+"\n")
    print('Split SHA-256:',manifest['split_sha256'])
    print('Source checkout:',head,'; available checkpoints:',sum(r['checkpoint_available'] for r in inventory))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update({"font.family":"DejaVu Sans", "font.size":11, "axes.titleweight":"bold"})
    runs = read_runs()
    images, _, _ = load_test()
    error_analysis(runs, images)
    extensions(runs)
    reproducibility(runs)
    print('Generated final report tables, 2 PNG/SVG figures, error audit and input manifest; no inference.')


if __name__ == "__main__":
    main()
